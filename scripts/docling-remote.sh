#!/usr/bin/env bash
# Bootstrap a remote Docling sidecar on a GPU host and tunnel it to
# localhost:1068 so `just worker` (unchanged) ingests through it.
#
# Expects the remote host to have:
#   - Docker with the NVIDIA runtime (`docker run --gpus all` works)
#   - git, rsync, SSH accessible
#
# On *your Mac* you need nothing special — SSH keys and a running
# `just infra-up` (or at least RabbitMQ + MinIO + Qdrant locally).
#
# Usage:
#   scripts/docling-remote.sh <ssh-target>                 # up (default)
#   scripts/docling-remote.sh <ssh-target> down            # tear down
#
# Example:
#   scripts/docling-remote.sh ubuntu@runpod-12345.ssh.runpod.io
#
# After `up` completes the sidecar is reachable locally on
# http://localhost:1068 (via SSH port-forward) and you can just run:
#   AGENT_RS__INGEST_BACKEND=docling just worker
#
# The tunnel runs in the foreground in a separate process; Ctrl-C the
# wrapper (or run `down`) to stop it.

set -euo pipefail

SSH_TARGET="${1:-}"
ACTION="${2:-up}"

if [[ -z "$SSH_TARGET" ]]; then
  cat <<EOF >&2
Usage: $0 <ssh-target> [up|down]

Example:
  $0 ubuntu@gpu-host                    # bootstrap + open tunnel
  $0 ubuntu@gpu-host down               # stop tunnel + stop remote sidecar

EOF
  exit 1
fi

# Local state — kept outside the repo so `git clean` doesn't blow it away.
STATE_DIR="$HOME/.cache/agent-rs/docling-remote"
mkdir -p "$STATE_DIR"
TUNNEL_PID_FILE="$STATE_DIR/tunnel.pid"
REMOTE_DIR="/home/$(ssh -o BatchMode=yes "$SSH_TARGET" 'whoami' 2>/dev/null || echo root)/agent-rs-docling"

LOCAL_PORT=1068
REMOTE_PORT=1068

green() { printf '\033[32m%s\033[0m\n' "$*"; }
red()   { printf '\033[31m%s\033[0m\n' "$*" >&2; }
info()  { printf '\033[36m%s\033[0m\n' "$*"; }

down() {
  info "→ closing SSH tunnel"
  if [[ -f "$TUNNEL_PID_FILE" ]]; then
    pid=$(cat "$TUNNEL_PID_FILE")
    kill "$pid" 2>/dev/null && green "   tunnel pid $pid stopped" || true
    rm -f "$TUNNEL_PID_FILE"
  else
    info "   (no tunnel pid file — nothing to stop locally)"
  fi
  info "→ stopping remote docling-sidecar container"
  ssh "$SSH_TARGET" 'cd '"$REMOTE_DIR"' && docker compose down docling-sidecar' \
    || red "   remote teardown failed (may already be down)"
  green "✓ docling-remote stopped"
}

up() {
  # ---- Sanity: local SSH reachable + remote has docker --------------
  info "→ checking SSH reachability"
  ssh -o BatchMode=yes -o ConnectTimeout=10 "$SSH_TARGET" 'echo ok' >/dev/null \
    || { red "SSH to $SSH_TARGET failed. Check your key/agent."; exit 1; }

  info "→ verifying remote has docker + nvidia runtime"
  ssh "$SSH_TARGET" 'docker run --rm --gpus all nvidia/cuda:12.4.0-base-ubuntu22.04 nvidia-smi | head -20' \
    || { red "remote docker --gpus all failed. Is the NVIDIA runtime installed?"; exit 1; }

  info "→ syncing Docling sidecar source to $SSH_TARGET:$REMOTE_DIR"
  ssh "$SSH_TARGET" "mkdir -p $REMOTE_DIR"
  # Only sync what the sidecar needs — proto + Dockerfile + python src.
  rsync -az --delete \
    --include='proto/***' \
    --include='infra/docling-sidecar/***' \
    --include='docker-compose.yml' \
    --exclude='*' \
    --include='*/' \
    "$PWD/" "$SSH_TARGET:$REMOTE_DIR/"

  # Minimal compose override so the remote only runs docling-sidecar.
  ssh "$SSH_TARGET" "cat > $REMOTE_DIR/docker-compose.override.yml" <<'YAML'
# Auto-generated by scripts/docling-remote.sh — do not edit.
# Strips every non-sidecar service so `docker compose up -d` starts only
# Docling on the remote host. Local MinIO/Qdrant/etc stay on the Mac.
services:
  docling-sidecar:
    runtime: nvidia
    environment:
      - DOCLING_ACCELERATOR=cuda
      - DOCLING_TABLEFORMER_MODE=accurate
      - NVIDIA_VISIBLE_DEVICES=all
YAML

  info "→ building + starting docling-sidecar on the remote (first run ≈ 5 min)"
  ssh "$SSH_TARGET" "cd $REMOTE_DIR && docker compose up -d --build docling-sidecar"

  info "→ waiting for the sidecar to report healthy"
  for i in {1..60}; do
    state=$(ssh "$SSH_TARGET" "docker inspect --format '{{.State.Health.Status}}' agentic-ra-docling-sidecar 2>/dev/null || echo starting")
    if [[ "$state" == "healthy" ]]; then
      green "   sidecar healthy after ${i}s"
      break
    fi
    sleep 1
    if (( i == 60 )); then
      red "   sidecar did not become healthy in 60s; check: ssh $SSH_TARGET 'docker logs agentic-ra-docling-sidecar'"
      exit 1
    fi
  done

  # Close any stale tunnel from a previous run.
  if [[ -f "$TUNNEL_PID_FILE" ]]; then
    old_pid=$(cat "$TUNNEL_PID_FILE")
    kill "$old_pid" 2>/dev/null || true
    rm -f "$TUNNEL_PID_FILE"
  fi

  info "→ opening SSH port-forward ${LOCAL_PORT} → remote:${REMOTE_PORT}"
  ssh -f -N -L "${LOCAL_PORT}:localhost:${REMOTE_PORT}" "$SSH_TARGET"
  # Record the new tunnel pid so `down` can stop it cleanly.
  tunnel_pid=$(pgrep -f "ssh -f -N -L ${LOCAL_PORT}:localhost:${REMOTE_PORT} $SSH_TARGET" | tail -1 || true)
  if [[ -n "$tunnel_pid" ]]; then
    echo "$tunnel_pid" > "$TUNNEL_PID_FILE"
    green "   tunnel pid $tunnel_pid written to $TUNNEL_PID_FILE"
  fi

  cat <<EOF

$(green '✓ Docling sidecar is live on a GPU box')

The sidecar is reachable locally at http://localhost:${LOCAL_PORT} via
SSH tunnel. Your Rust worker's default endpoint (same URL) needs no
change — run it as usual:

    just worker

When you are done:

    scripts/docling-remote.sh $SSH_TARGET down

EOF
}

case "$ACTION" in
  up)   up ;;
  down) down ;;
  *)    red "Unknown action '$ACTION'. Use 'up' or 'down'."; exit 1 ;;
esac
