-- Strategy performance tracking (spec D1).
-- Logs the outcome of every retrieval query so the system can learn
-- which strategies work best for different query intents over time.

CREATE TABLE strategy_performance (
    id                  BIGSERIAL       PRIMARY KEY,

    -- Query fingerprint (SHA-256 of normalized query text).
    query_hash          CHAR(64)        NOT NULL,

    -- LLM-classified intent from QueryRewriter / QueryAnalyzer.
    query_intent        TEXT            NULL,

    -- Which retrieval strategy was used.
    strategy            TEXT            NOT NULL,

    -- Number of evidence documents returned.
    evidence_count      INTEGER         NOT NULL DEFAULT 0,

    -- Average relevance score of top-5 results (0.0 – 1.0).
    avg_relevance_score REAL            NULL,

    -- Whether the grounding verifier passed.
    is_grounded         BOOLEAN         NULL,

    -- Verifier confidence score (0.0 – 1.0).
    confidence          REAL            NULL,

    -- End-to-end retrieval latency in milliseconds.
    latency_ms          BIGINT          NOT NULL DEFAULT 0,

    -- Whether a retry was needed after initial retrieval.
    required_retry      BOOLEAN         NOT NULL DEFAULT FALSE,

    -- Number of sub-queries generated by query rewriter.
    sub_query_count     INTEGER         NOT NULL DEFAULT 1,

    -- Whether HyDE was used for embedding.
    used_hyde           BOOLEAN         NOT NULL DEFAULT FALSE,

    -- Whether metadata filters were applied.
    used_metadata_filter BOOLEAN        NOT NULL DEFAULT FALSE,

    -- Whether context expansion was applied.
    used_context_expansion BOOLEAN      NOT NULL DEFAULT FALSE,

    -- Number of entities linked to KG nodes.
    linked_entities     INTEGER         NOT NULL DEFAULT 0,

    created_at          TIMESTAMP       NOT NULL DEFAULT NOW()
);

-- Index for aggregation queries: "which strategy works best for intent X?"
CREATE INDEX idx_strategy_perf_intent_strategy
    ON strategy_performance (query_intent, strategy);

-- Index for time-range queries: "performance over the last 7 days"
CREATE INDEX idx_strategy_perf_created
    ON strategy_performance (created_at DESC);

-- Index for per-strategy aggregation
CREATE INDEX idx_strategy_perf_strategy
    ON strategy_performance (strategy);
